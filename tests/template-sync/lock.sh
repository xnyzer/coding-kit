# lock-check cases for tests/template-sync/run.sh — sourced after sync.sh, uses its
# fixture helpers. The fixtures follow what `mise lock` writes (lockfile format 3); no
# network and no mise needed.

# $TMP/NAME.tsv has the line made of the FIELDs, joined by tabs.
lock_line() {  # NAME FIELD…
  ll_name=$1
  shift
  ll_line=$1
  shift
  for ll_f in "$@"; do ll_line="$ll_line$TAB_CHAR$ll_f"; done
  grep -qxF -- "$ll_line" "$TMP/$ll_name.tsv"
}

# $TMP/NAME.tsv has no line starting with KIND.
no_kind() {  # NAME KIND
  ! cut -f1 "$TMP/$1.tsv" | grep -qxF -- "$2"
}

run_lock_cases() {
  TAB_CHAR=$(printf '\t')
  MISE_TOML='[tools]\njust = "1"\nnode = ["22", "24"]\n"npm:prettier" = "3"\n"cargo:tokei" = "12"\n"github:BurntSushi/ripgrep" = "14"\nlefthook = "2"\npython = "3.13"\nuv = "0"\n\n[tools.go]\nversion = "1.26"\n\n[settings]\nlockfile = true\nlockfile_platforms = [\n  "linux-x64",  # CI\n  "macos-arm64",\n  '"'"'windows-x64'"'"',\n]\n'
  plat() {  # TOOL PLATFORM — a platform table as mise writes it
    printf '[tools.%s."platforms.%s"]\nchecksum = "sha256:00"\nurl = "https://example.com/%s"\n\n' "$1" "$2" "$2"
  }
  {
    printf '# @generated - this file is auto-generated by `mise lock`\n\nlockfile_version = 3\n\n'
    printf '[[tools."cargo:tokei"]]\nversion = "12.1.2"\nbackend = "cargo:tokei"\nspecifiers = ["12"]\n\n'
    printf '[[tools."github:BurntSushi/ripgrep"]]\nversion = "14.1.1"\nbackend = "github:BurntSushi/ripgrep"\nspecifiers = ["14"]\n\n'
    plat '"github:BurntSushi/ripgrep"' linux-x64
    plat '"github:BurntSushi/ripgrep"' macos-arm64
    plat '"github:BurntSushi/ripgrep"' windows-x64
    printf '[[tools.gitleaks]]\nversion = "8.30.1"\nbackend = "aqua:gitleaks/gitleaks"\n\n'
    plat gitleaks linux-x64
    printf '[[tools.just]]\nversion = "1.55.1"\nbackend = "aqua:casey/just"\nspecifiers = ["1"]\n\n'
    plat just linux-x64
    plat just macos-arm64
    plat just windows-x64
    printf '[[tools.lefthook]]\nversion = "2.2.1"\nbackend = "aqua:evilmartians/lefthook"\n\n'
    plat lefthook macos-arm64
    plat lefthook windows-x64
    printf '[[tools.node]]\nversion = "22.23.2"\nbackend = "core:node"\n\n'
    plat node linux-x64
    plat node macos-arm64
    plat node windows-x64
    printf '[[tools.node]]\nversion = "24.19.0"\nbackend = "core:node"\n\n'
    plat node linux-x64
    plat node macos-arm64
    printf '[[tools."npm:prettier"]]\nversion = "3.9.10"\naube = { path = ".mise/locks/npm-prettier/3.9.10", digest = "sha256:00" }\nbackend = "npm:prettier"\n\n'
    printf '[[tools.python]]\nversion = "3.13.9"\nbackend = "core:python"\n\n'
  } > "$TMP/lock.fixture"

  # --- one project, every tool state ------------------------------------------------
  put lk/mise.toml "$MISE_TOML"
  cp "$TMP/lock.fixture" "$TMP/lk/mise.lock"
  put lk/.github/workflows/ci.yml 'jobs:\n  check:\n    runs-on: ubuntu-latest\n    steps:\n      - uses: jdx/mise-action@0000 # v4\n'
  put lk/.github/workflows/codeql.yml 'jobs:\n  analyze:\n    runs-on: macos-14\n'
  check "lock-check runs" eval 'ts lock-check "$TMP/lk" > "$TMP/l.tsv"'
  check "lock-check: platforms, multi-line with comment and quotes" \
    lock_line l platforms linux-x64,macos-arm64,windows-x64
  check "lock-check: CI platform from the mise workflow" \
    lock_line l ci linux-x64 ubuntu-latest .github/workflows/ci.yml
  refute "lock-check: workflow without mise-action ignored" grep -q 'macos-14' "$TMP/l.tsv"
  check "lock-check: all platforms present" lock_line l tool just 1.55.1 complete -
  check "lock-check: quoted tool and platform keys" \
    lock_line l tool github:BurntSushi/ripgrep 14.1.1 complete -
  check "lock-check: gap off the CI platform" lock_line l tool node 24.19.0 gaps windows-x64
  check "lock-check: one line per locked version" lock_line l tool node 22.23.2 complete -
  check "lock-check: gap on the CI platform" lock_line l tool lefthook 2.2.1 ci-gap linux-x64
  check "lock-check: entry without platform tables (mise install alone)" \
    lock_line l tool python 3.13.9 ci-gap linux-x64,macos-arm64,windows-x64
  check "lock-check: npm records no URL" lock_line l tool npm:prettier 3.9.10 no-url -
  check "lock-check: cargo records no URL" lock_line l tool cargo:tokei 12.1.2 no-url -
  check "lock-check: configured, not locked" lock_line l tool uv - unlocked -
  check "lock-check: [tools.NAME] table counts as configured" lock_line l tool go - unlocked -
  check "lock-check: locked, no longer configured" lock_line l tool gitleaks 8.30.1 stale -
  check "lock-check: header lines first" test "$(sed -n 1p "$TMP/l.tsv" | cut -f1)" = platforms
  check "lock-check: tools sorted by name" \
    test "$(grep '^tool' "$TMP/l.tsv" | cut -f2 | tr '\n' ' ')" = \
    "cargo:tokei github:BurntSushi/ripgrep gitleaks go just lefthook node node npm:prettier python uv "

  # --- single-line setting, no CI, CRLF -------------------------------------------------
  put lo/mise.toml '[tools]\r\njust = "1"\r\n\r\n[settings]\r\nlockfile_platforms = ["linux-x64", "macos-arm64"]\r\n'
  put lo/mise.lock '[[tools.just]]\r\nversion = "1.55.1"\r\nbackend = "aqua:casey/just"\r\n\r\n[tools.just."platforms.macos-arm64"]\r\nurl = "https://example.com/x"\r\n'
  check "lock-check without CI runs" eval 'ts lock-check "$TMP/lo" > "$TMP/lo.tsv"'
  check "lock-check: single-line setting" lock_line lo platforms linux-x64,macos-arm64
  check "lock-check: no mise workflow" lock_line lo ci none
  check "lock-check: without CI a gap does not block" lock_line lo tool just 1.55.1 gaps linux-x64

  # --- missing setting, missing lock file ----------------------------------------------
  put lm/mise.toml '[tools]\njust = "1"\n\n[settings]\nlockfile = true\n'
  cp "$TMP/lock.fixture" "$TMP/lm/mise.lock"
  check "lock-check without the setting runs" eval 'ts lock-check "$TMP/lm" > "$TMP/lm.tsv"'
  check "lock-check: setting missing" lock_line lm platforms missing
  check "lock-check: without the setting no tool lines" no_kind lm tool
  put ln/mise.toml "$MISE_TOML"
  check "lock-check without a lock file runs" eval 'ts lock-check "$TMP/ln" > "$TMP/ln.tsv"'
  check "lock-check: lock file missing" lock_line ln lockfile missing
  check "lock-check: without a lock file no tool lines" no_kind ln tool
  mkdir -p "$TMP/lx"
  refute "lock-check: project without mise.toml refused" ts lock-check "$TMP/lx"
  refute "lock-check: missing project refused" ts lock-check "$TMP/nope"
  refute "lock-check: takes one project" ts lock-check "$TMP/lk" "$TMP/lo"

  # --- a platform table after another tool's entry (TOML: it belongs to its own tool) ---
  put lt/mise.toml '[tools]\njust = "1"\nnode = "24"\n\n[settings]\nlockfile_platforms = ["linux-x64"]\n'
  put lt/mise.lock '[[tools.just]]\nversion = "1.55.1"\nbackend = "aqua:casey/just"\n\n[[tools.node]]\nversion = "24.19.0"\nbackend = "core:node"\n\n[tools.just."platforms.linux-x64"]\nurl = "u"\n'
  check "lock-check with a late platform table runs" eval 'ts lock-check "$TMP/lt" > "$TMP/lt.tsv"'
  check "lock-check: late table counts for its own tool" lock_line lt tool just 1.55.1 complete -
  check "lock-check: late table not for the entry above it" lock_line lt tool node 24.19.0 gaps linux-x64

  # --- runner labels -------------------------------------------------------------------
  put lr/mise.toml '[tools]\njust = "1"\n\n[settings]\nlockfile_platforms = ["linux-x64"]\n'
  put lr/mise.lock '[[tools.just]]\nversion = "1"\nbackend = "aqua:casey/just"\n\n[tools.just."platforms.linux-x64"]\nurl = "u"\n'
  put lr/.github/workflows/matrix.yaml "jobs:\n  a:\n    runs-on: ubuntu-24.04\n  b:\n    runs-on: ubuntu-24.04-arm\n  c:\n    runs-on: macos-15-intel\n  d:\n    runs-on: macos-14-large\n  e:\n    runs-on: macos-14-xlarge\n  f:\n    runs-on: macos-latest\n  g:\n    runs-on: 'windows-latest'\n  h:\n    runs-on: \"windows-11-arm\"\n  i:\n    runs-on: \${{ matrix.os }}\n  j:\n    runs-on: [self-hosted, linux]\n  k:\n    runs-on: macos-13\n    steps:\n      - uses: jdx/mise-action@0000\n"
  check "lock-check with runner labels runs" eval 'ts lock-check "$TMP/lr" > "$TMP/lr.tsv"'
  check "runner: ubuntu" lock_line lr ci linux-x64 ubuntu-24.04 .github/workflows/matrix.yaml
  check "runner: ubuntu arm" lock_line lr ci linux-arm64 ubuntu-24.04-arm .github/workflows/matrix.yaml
  check "runner: macOS Intel" lock_line lr ci macos-x64 macos-15-intel .github/workflows/matrix.yaml
  check "runner: macOS large (Intel)" lock_line lr ci macos-x64 macos-14-large .github/workflows/matrix.yaml
  check "runner: macOS xlarge (arm64)" lock_line lr ci macos-arm64 macos-14-xlarge .github/workflows/matrix.yaml
  check "runner: macOS latest" lock_line lr ci macos-arm64 macos-latest .github/workflows/matrix.yaml
  check "runner: macOS 13" lock_line lr ci macos-x64 macos-13 .github/workflows/matrix.yaml
  check "runner: windows, quoted" lock_line lr ci windows-x64 windows-latest .github/workflows/matrix.yaml
  check "runner: windows arm" lock_line lr ci windows-arm64 windows-11-arm .github/workflows/matrix.yaml
  check "runner: expression is unknown" \
    lock_line lr ci unknown '${{ matrix.os }}' .github/workflows/matrix.yaml
  check "runner: self-hosted is unknown" \
    lock_line lr ci unknown '[self-hosted, linux]' .github/workflows/matrix.yaml
}
